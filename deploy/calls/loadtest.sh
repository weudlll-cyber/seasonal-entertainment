#!/bin/bash
# ============================================================
# File:        loadtest.sh
# Path:        deploy/calls/loadtest.sh
# Project:     Seasonal Entertainment
# Description: A load test of the call service for the owner to run on the VPS (docs/CALLS.md,
#              "Load test"): sudo ./deploy/calls/loadtest.sh. Three steps of 3 minutes, each
#              with 3 video publishers (2 cameras and a screen share; the CLI has no screen
#              share, so it is a third video publisher at high resolution) and 2 audio
#              publishers, and 25, then 50, then 100 subscribers, generated by LiveKit's CLI
#              (pinned by digest) on the host network against ws://127.0.0.1:7880, its container
#              capped at 2 CPUs and 2 GB. Every 10 s it samples docker stats of LiveKit, egress
#              and the site, the 1-minute load and the free memory; it stops at once when the
#              load passes 5, the free memory drops under 1.5 GB, on Ctrl-C, or after 20 minutes
#              in all. The keys come from deploy/calls/.env and are never printed. Only its own
#              containers (se-loadtest-*, all --rm) and rooms are started and removed; nothing
#              else on the server is touched. Prints a table per step and the full log's path.
#              --dry-run prints the plan and checks the keys exist, running nothing (the test,
#              deploy/test/loadtest.test.sh). The generator shares the host: the numbers are
#              pessimistic.
# ============================================================

set -Euo pipefail

CALLS_DIR="${SE_LOADTEST_CALLS_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
SITE_DIR="${SE_LOADTEST_SITE_DIR:-$CALLS_DIR/../site}"
# livekit-cli 2.19.3 (lk version), by digest only.
CLI_IMAGE='livekit/livekit-cli@sha256:cb460d18fb001c81fb3b6c9bf8fee487e64fb64124f3495086823ac5cd0b7a81'
URL='ws://127.0.0.1:7880'
SUBSCRIBERS=(25 50 100)
VIDEO_PUBLISHERS=3
AUDIO_PUBLISHERS=2
STEP_SECONDS=180
SAMPLE_SECONDS=10
MAX_LOAD=5
MIN_FREE_KB=$((1536 * 1024)) # 1.5 GB
TOTAL_SECONDS=1200
RUN_ID="se-loadtest-$(date +%Y%m%d-%H%M%S)"

say() { printf '[loadtest] %s\n' "$*"; }
die() { printf '[loadtest] STOPPED: %s\n' "$*" >&2; exit 1; }

DRY_RUN=no
case "${1:-}" in
  --dry-run) DRY_RUN=yes ;;
  '') ;;
  *) die "unknown option $1 (only --dry-run)" ;;
esac

# The keys, never printed: LIVEKIT_API_KEY/SECRET (with recording), else LIVEKIT_KEYS ("key: secret").
ENV_SOURCE="$CALLS_DIR/.env"
[[ -r "$ENV_SOURCE" ]] || die "$ENV_SOURCE is missing or not readable (run with sudo)"
read_key() { sed -n "s/^$1=//p" "$ENV_SOURCE" | tail -n 1; }
api_key="$(read_key LIVEKIT_API_KEY)"
api_secret="$(read_key LIVEKIT_API_SECRET)"
if [[ -z "$api_key" || -z "$api_secret" ]]; then
  keys="$(read_key LIVEKIT_KEYS)"
  [[ "$keys" == *:* ]] || die "no LiveKit key in $ENV_SOURCE (LIVEKIT_API_KEY/SECRET or LIVEKIT_KEYS)"
  api_key="${keys%%:*}"
  api_secret="${keys#*:}"
  api_secret="${api_secret#"${api_secret%%[![:space:]]*}"}"
fi
[[ -n "$api_key" && -n "$api_secret" ]] ||
  die "no LiveKit key in $ENV_SOURCE (LIVEKIT_API_KEY/SECRET or LIVEKIT_KEYS)"

# One step's generator, as an argument list (the keys only through --env-file).
step_command() {
  local subscribers="$1" env_file="$2"
  echo docker run --rm --name "$RUN_ID-$subscribers" --network host --cpus 2 --memory 2g \
    --env-file "$env_file" "$CLI_IMAGE" load-test --url "$URL" --room "$RUN_ID-$subscribers" \
    --video-publishers "$VIDEO_PUBLISHERS" --audio-publishers "$AUDIO_PUBLISHERS" \
    --subscribers "$subscribers" --duration "${STEP_SECONDS}s"
}

if [[ "$DRY_RUN" == yes ]]; then
  say "dry run: nothing is started. Keys found in $ENV_SOURCE (not shown)."
  for n in "${SUBSCRIBERS[@]}"; do say "step $n subscribers: $(step_command "$n" '<a temporary file, mode 600>')"; done
  say "samples every ${SAMPLE_SECONDS}s; stops when the 1-min load > $MAX_LOAD or free memory < 1.5 GB, on Ctrl-C, after ${TOTAL_SECONDS}s in all"
  exit 0
fi

[[ "$(id -u)" == 0 ]] || die "run as root: sudo $0"
command -v docker >/dev/null || die "docker is not installed"
LOG="/var/log/$RUN_ID.log"
WORK="$(mktemp -d)"
ENV_FILE="$WORK/keys.env"
(umask 077 && printf 'LIVEKIT_API_KEY=%s\nLIVEKIT_API_SECRET=%s\n' "$api_key" "$api_secret" >"$ENV_FILE")
unset api_key api_secret keys
current=""
aborted=""

# Only this run's own: its running generator, its rooms, its temporary keys.
cleanup() {
  [[ -z "$current" ]] || docker stop -t 2 "$current" >/dev/null 2>&1 || true
  for n in "${SUBSCRIBERS[@]}"; do
    docker run --rm --network host --env-file "$ENV_FILE" "$CLI_IMAGE" room delete \
      --url "$URL" "$RUN_ID-$n" >/dev/null 2>&1 || true
  done
  rm -rf "$WORK"
}
trap 'aborted="Ctrl-C"; cleanup; say "stopped by Ctrl-C; log: $LOG"; exit 130' INT TERM
trap cleanup EXIT

# The containers to watch, by their compose service (empty when one is not running).
container_of() { (cd "$1" && docker compose ps -q "$2" 2>/dev/null) | head -n 1; }
LIVEKIT="$(container_of "$CALLS_DIR" livekit)"
EGRESS="$(container_of "$CALLS_DIR" egress)"
SITE="$(container_of "$SITE_DIR" site)"
[[ -n "$LIVEKIT" ]] || die "the LiveKit container is not running (deploy/calls)"

free_kb() { sed -n 's/^MemAvailable: *\([0-9]*\) kB/\1/p' /proc/meminfo; }
load1() { cut -d' ' -f1 /proc/loadavg; }
# The CPU % of LiveKit, egress and the site now, from one docker stats call (one sample each;
# 0 for one that is not running), as "livekit egress site".
WATCHED=()
for id in "$LIVEKIT" "$EGRESS" "$SITE"; do [[ -z "$id" ]] || WATCHED+=("$id"); done
cpus() {
  local stats id line
  stats="$(docker stats --no-stream --format '{{.Container}} {{.CPUPerc}}' "${WATCHED[@]}" 2>/dev/null)"
  for id in "$LIVEKIT" "$EGRESS" "$SITE"; do
    line="$([[ -n "$id" ]] && awk -v id="$id" '$1 == id { gsub(/%/, "", $2); print $2 }' <<<"$stats")"
    printf '%s ' "${line:-0}"
  done
}

started=$SECONDS
table="step  livekit cpu % peak/avg  egress peak  site peak  load max  free MB min  tracks  loss  errors"
say "log: $LOG"
for n in "${SUBSCRIBERS[@]}"; do
  [[ -z "$aborted" ]] || break
  out="$WORK/step-$n.out"
  read -ra cmd <<<"$(step_command "$n" "$ENV_FILE")"
  say "step: $VIDEO_PUBLISHERS video + $AUDIO_PUBLISHERS audio publishers, $n subscribers, ${STEP_SECONDS}s"
  "${cmd[@]}" >"$out" 2>&1 &
  pid=$!
  current="$RUN_ID-$n"
  lk_peak=0 lk_sum=0 eg_peak=0 site_peak=0 load_max=0 free_min=999999999 samples=0
  while kill -0 "$pid" 2>/dev/null; do
    sleep "$SAMPLE_SECONDS"
    kill -0 "$pid" 2>/dev/null || break
    read -r lk eg st <<<"$(cpus)"
    load="$(load1)" free="$(free_kb)"
    samples=$((samples + 1))
    lk_sum="$(awk -v a="$lk_sum" -v b="$lk" 'BEGIN { print a + b }')"
    lk_peak="$(awk -v a="$lk_peak" -v b="$lk" 'BEGIN { print (b > a ? b : a) }')"
    eg_peak="$(awk -v a="$eg_peak" -v b="$eg" 'BEGIN { print (b > a ? b : a) }')"
    site_peak="$(awk -v a="$site_peak" -v b="$st" 'BEGIN { print (b > a ? b : a) }')"
    load_max="$(awk -v a="$load_max" -v b="$load" 'BEGIN { print (b > a ? b : a) }')"
    ((free < free_min)) && free_min=$free
    printf '%s step=%s livekit=%s egress=%s site=%s load1=%s freeKB=%s\n' "$(date -Is)" "$n" \
      "$lk" "$eg" "$st" "$load" "$free" >>"$LOG"
    if awk -v l="$load" -v m="$MAX_LOAD" 'BEGIN { exit !(l > m) }'; then aborted="load $load > $MAX_LOAD"; fi
    ((free < MIN_FREE_KB)) && aborted="free memory $((free / 1024)) MB < 1536 MB"
    ((SECONDS - started > TOTAL_SECONDS)) && aborted="the ${TOTAL_SECONDS}s limit"
    if [[ -n "$aborted" ]]; then
      say "stopping at once: $aborted"
      docker stop -t 2 "$current" >/dev/null 2>&1 || true
      break
    fi
  done
  wait "$pid" 2>/dev/null || true
  current=""
  cat "$out" >>"$LOG"
  # The CLI's "Total" row of its subscriber summary: tracks, packet loss, errors.
  total="$(grep -E '│ Total' "$out" | tail -n 1 | awk -F'│' '{ gsub(/ /, "", $3); gsub(/^ +| +$/, "", $5); gsub(/ /, "", $6); print $3 "|" $5 "|" $6 }')"
  IFS='|' read -r tracks loss errors <<<"${total:-?|?|?}"
  avg="$(awk -v s="$lk_sum" -v n="$samples" 'BEGIN { printf "%.0f", (n ? s / n : 0) }')"
  table+=$'\n'"$(printf '%-5s %10s/%-12s %11s %10s %9s %12s  %-6s %-5s %s' "$n" "$lk_peak" "$avg" \
    "$eg_peak" "$site_peak" "$load_max" "$((free_min / 1024))" "$tracks" "$loss" "$errors")"
done

echo
echo "$table"
echo
[[ -z "$aborted" ]] || say "stopped early: $aborted"
say "full log: $LOG (the generator shares this host, so the numbers are pessimistic)"
